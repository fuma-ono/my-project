-- data-sources.md §6.4 (HQ指示 2026-10-16): 外部APIのクレジット(呼び出し回数)台帳。
--
-- 定期実行・手動実行・eval:providers が同時に動いても、1日(UTC)の上限を
-- 超えないようにするため、HTTPの1回ごと(再試行を含む)に、送る前に
-- reserve_api_credits() で1クレジットを予約する。予約できなければ送らない。
--
-- 上限(p_cap)は呼び出し側が渡す(src/ingestion/config.ts API_CREDIT_CAPS):
--   Twelve Data 定期実行 700 / 手動実行・eval:providers 800。
-- 日付の区切りは UTC 00:00(Twelve Data の日次リセットと同じ)。

create table api_credit_usage (
  id bigint generated by default as identity primary key,
  provider text not null,
  usage_date date not null,
  job text not null,
  run_id text not null,
  credits integer not null check (credits > 0),
  cap integer not null check (cap > 0),
  reserved_at timestamptz not null default now()
);

comment on table api_credit_usage is
  '外部APIのクレジット予約台帳(1行=予約1回)。reserve_api_credits() からのみ書き込む。';
comment on column api_credit_usage.usage_date is 'UTCの日付。この日付ごとに上限を判定する。';
comment on column api_credit_usage.run_id is 'ジョブ実行ごとのID(GITHUB_RUN_ID など)。どの実行が使ったかの追跡用。';
comment on column api_credit_usage.cap is '予約したときに適用された1日の上限(定期 700 / 手動 800 など)。';

create index idx_api_credit_usage_provider_date on api_credit_usage(provider, usage_date);

-- 運用データ。ingestion_logs と同じくポリシーなし(service_role のみ)。
alter table api_credit_usage enable row level security;
revoke all on table api_credit_usage from public, anon, authenticated;

-- 予約: 同じ取得元・同じ日付の予約を advisory lock で1本ずつ処理するので、
-- 同時に呼ばれても「今日の合計 + p_credits <= p_cap」の判定と追加の間に
-- 割り込まれない。予約できたら true、上限を超えるなら何も追加せず false。
create function reserve_api_credits(
  p_provider text,
  p_job text,
  p_run_id text,
  p_credits integer,
  p_cap integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_date date := (now() at time zone 'utc')::date;
  v_used bigint;
begin
  if p_credits is null or p_credits <= 0 then
    raise exception 'p_credits must be positive' using errcode = '22023';
  end if;
  if p_cap is null or p_cap <= 0 then
    raise exception 'p_cap must be positive' using errcode = '22023';
  end if;

  -- トランザクションの終わりまで保持されるロック(関数の呼び出し1回 = 1トランザクション)。
  perform pg_advisory_xact_lock(hashtext(p_provider || ':' || v_date::text));

  select coalesce(sum(credits), 0) into v_used
    from api_credit_usage
    where provider = p_provider and usage_date = v_date;

  if v_used + p_credits > p_cap then
    return false;
  end if;

  insert into api_credit_usage (provider, usage_date, job, run_id, credits, cap)
    values (p_provider, v_date, p_job, p_run_id, p_credits, p_cap);
  return true;
end;
$$;

-- 今日(UTC)の使用量(全ジョブの合計)。計画を立てるときの参考値で、上限の判定は reserve_api_credits() が行う。
create function api_credits_used_today(p_provider text)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(credits), 0)::integer
    from api_credit_usage
    where provider = p_provider and usage_date = (now() at time zone 'utc')::date;
$$;

-- service_role (the Backend / ingestion jobs) only — never callable by app users directly.
revoke all on function reserve_api_credits(text, text, text, integer, integer) from public, anon, authenticated;
grant execute on function reserve_api_credits(text, text, text, integer, integer) to service_role;
revoke all on function api_credits_used_today(text) from public, anon, authenticated;
grant execute on function api_credits_used_today(text) to service_role;
