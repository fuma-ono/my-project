-- data-sources.md §6.4.1 (HQ指示 2026-10-16): 外部APIのクレジット(呼び出し回数)台帳。
--
-- 定期実行・手動実行・eval:providers が同時に動いても、1日(UTC)の上限を
-- 超えないようにするため、HTTPの1回ごと(再試行を含む)に、送る前に
-- reserve_api_credits() で1クレジットを予約する。予約できなければ送らない。
--
-- 上限は DB が持つ(api_credit_limits)。呼び出し側は「自動か手動か」だけを渡し、上限の値は渡さない
-- (HQ判断 2026-10-16「全実行の合計 800/日、自動 700/日。自動と手動が別枠で 1,500 になる設計は認めない」)。
--   - 合計の判定は、その日の全部の予約(自動・手動・eval:providers)を足したもの
--   - AUTOMATIC: 合計 + 予約 ≦ automatic_cap(700)のときだけ予約できる → 自動は最大 700、手動のために最低 100 残る
--   - MANUAL:    合計 + 予約 ≦ daily_total_cap(800)のときだけ予約できる → 手動は 800 − その日の予約済み
--   - 上限の行が無い取得元は予約できない(エラー)
-- 予約は解放しない(送った後のタイムアウト・再試行・途中で止まった実行の分も、実際に消費したか分からないため数えたままにする)。
-- 日付の区切りは UTC 00:00(Twelve Data の日次リセットと同じ)。
--
-- SQL Editor で手で流しても、2回目以降は何も変えずに終わるように書く(if not exists / create or replace / on conflict)。

create table if not exists api_credit_limits (
  provider text primary key,
  daily_total_cap integer not null check (daily_total_cap > 0),
  automatic_cap integer not null check (automatic_cap > 0),
  updated_at timestamptz not null default now(),
  check (automatic_cap <= daily_total_cap)
);

comment on table api_credit_limits is
  '外部APIの1日(UTC)のクレジット上限。daily_total_cap = 全実行の合計、automatic_cap = 自動実行が予約できる合計の上限。';

-- Twelve Data Basic(無料)プラン: 800 クレジット/日(公式 support 記事、2026-10-16 確認)。契約を変えたらここを直す。
insert into api_credit_limits (provider, daily_total_cap, automatic_cap)
values ('twelvedata', 800, 700)
on conflict (provider) do nothing;

create table if not exists api_credit_usage (
  id bigint generated by default as identity primary key,
  provider text not null,
  usage_date date not null,
  job text not null,
  run_id text not null,
  mode text not null check (mode in ('AUTOMATIC', 'MANUAL')),
  credits integer not null check (credits > 0),
  cap integer not null check (cap > 0),
  reserved_at timestamptz not null default now()
);

comment on table api_credit_usage is
  '外部APIのクレジット予約台帳(1行=予約1回)。reserve_api_credits() からのみ書き込む。解放(削除)しない。';
comment on column api_credit_usage.usage_date is 'UTCの日付。この日付ごとに上限を判定する。';
comment on column api_credit_usage.run_id is 'ジョブ実行ごとのID(GITHUB_RUN_ID など)。どの実行が使ったかの追跡用。';
comment on column api_credit_usage.mode is 'AUTOMATIC = 定期実行、MANUAL = 手動実行・eval:providers。';
comment on column api_credit_usage.cap is '予約したときに適用された上限(api_credit_limits の automatic_cap か daily_total_cap)。記録用。';

create index if not exists idx_api_credit_usage_provider_date on api_credit_usage(provider, usage_date);

-- 運用データ。ingestion_logs と同じくポリシーなし(service_role のみ)。
alter table api_credit_limits enable row level security;
alter table api_credit_usage enable row level security;
revoke all on table api_credit_limits from public, anon, authenticated;
revoke all on table api_credit_usage from public, anon, authenticated;

create or replace function reserve_api_credits(
  p_provider text,
  p_job text,
  p_run_id text,
  p_credits integer,
  p_mode text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_date date := (now() at time zone 'utc')::date;
  v_total_cap integer;
  v_automatic_cap integer;
  v_cap integer;
  v_used bigint;
begin
  if p_credits is null or p_credits <= 0 then
    raise exception 'p_credits must be positive' using errcode = '22023';
  end if;
  if p_mode is null or p_mode not in ('AUTOMATIC', 'MANUAL') then
    raise exception 'p_mode must be AUTOMATIC or MANUAL' using errcode = '22023';
  end if;

  select daily_total_cap, automatic_cap into v_total_cap, v_automatic_cap
    from api_credit_limits
    where provider = p_provider;
  if not found then
    raise exception 'no credit limit configured for provider %', p_provider using errcode = '22023';
  end if;
  v_cap := case when p_mode = 'AUTOMATIC' then least(v_automatic_cap, v_total_cap) else v_total_cap end;

  -- トランザクションの終わりまで保持されるロック(関数の呼び出し1回 = 1トランザクション)。
  -- 同じ取得元・同じ日の予約は1つずつ順番に判定される。
  perform pg_advisory_xact_lock(hashtext(p_provider || ':' || v_date::text));

  select coalesce(sum(credits), 0) into v_used
    from api_credit_usage
    where provider = p_provider and usage_date = v_date;

  if v_used + p_credits > v_cap then
    return false;
  end if;

  insert into api_credit_usage (provider, usage_date, job, run_id, mode, credits, cap)
    values (p_provider, v_date, p_job, p_run_id, p_mode, p_credits, v_cap);
  return true;
end;
$$;

create or replace function api_credits_used_today(p_provider text)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(credits), 0)::integer
    from api_credit_usage
    where provider = p_provider and usage_date = (now() at time zone 'utc')::date;
$$;

revoke all on function reserve_api_credits(text, text, text, integer, text) from public, anon, authenticated;
grant execute on function reserve_api_credits(text, text, text, integer, text) to service_role;
revoke all on function api_credits_used_today(text) from public, anon, authenticated;
grant execute on function api_credits_used_today(text) to service_role;
