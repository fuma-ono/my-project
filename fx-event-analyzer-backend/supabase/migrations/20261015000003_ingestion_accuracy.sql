-- データ取得(Ingestion Worker)の正確性の仕組み(db-design.md v4.15 §3.6 / §3.11 / §3.13 / §3.20 / §3.21、
-- data-sources.md)。
--
-- 方針: 確かめきれていない値は Read API が読むテーブル(event_snapshots)に入れない。
-- RELEASE スナップショットは不変(20260917000005)なので、誤った値を一度入れると直せない。
-- そのため検証前の値は ingestion_staged_values に置き、検証を通った値だけを
-- event_snapshots(RELEASE)に入れる。Read API は ingestion_staged_values を読まないので、
-- 検証待ち・要確認の値は利用者に見えず、イベントは data_status = PENDING(API では DATA_PENDING)のまま。

-- ---------------------------------------------------------------------
-- 1. event_snapshots: どう確かめた値か
-- ---------------------------------------------------------------------
-- 既存の行(開発用 seed・手入力)は人が確認した値として VERIFIED にする。既存の API 応答は変わらない。
alter table event_snapshots
  add column verification_status text not null default 'VERIFIED'
    check (verification_status in ('VERIFIED', 'SINGLE_SOURCE')),
  add column verification_source text,
  add column official_actual numeric(18, 4);

comment on column event_snapshots.verification_status is
  'VERIFIED = 公式統計(FRED/BLS等)の値と丸めを合わせて一致した、または人が確認した。SINGLE_SOURCE = 照合できる公式統計がなく、取得元1つの値(指標の対応表で許可した指標だけ)。';
comment on column event_snapshots.verification_source is
  '照合に使った公式統計。例: ''FRED:CPIAUCNS@2026-10-14''(系列ID@時点)。SINGLE_SOURCE は null。';
comment on column event_snapshots.official_actual is
  '照合に使った公式統計から計算した値(丸め前)。SINGLE_SOURCE は null。';

-- ---------------------------------------------------------------------
-- 2. ingestion_staged_values: 検証待ち・要確認の値(Read API は読まない)
-- ---------------------------------------------------------------------
create table ingestion_staged_values (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references economic_events(id) on delete restrict,
  -- RELEASE = 発表値(まだ event_snapshots に無い)、REVISION = 発表後の改定(event_revisions の候補)
  kind text not null check (kind in ('RELEASE', 'REVISION')),
  -- REVISION のとき改定された項目(event_revisions.field_name と同じ値)
  revision_field text check (revision_field in ('ACTUAL', 'PREVIOUS')),
  provider text not null,
  provider_event_id text not null,
  indicator_code text not null,
  -- 対象期間('YYYY-MM' 等)。公式統計との照合に使う
  reference_period text,
  forecast numeric(18, 4),
  actual numeric(18, 4),
  previous numeric(18, 4),
  -- REVISION のとき: 改定前(event_snapshots の値)と改定後
  old_value numeric(18, 4),
  new_value numeric(18, 4),
  unit text,
  source text,
  source_url text,
  release_status text not null default 'UNKNOWN' check (release_status in ('PRELIMINARY', 'REVISED', 'FINAL', 'UNKNOWN')),
  fetched_at timestamptz not null,
  official_actual numeric(18, 4),
  official_source text,
  -- AWAITING_OFFICIAL = 検証は通ったが公式統計がまだ出ていない(ingest:official が再照合する)
  -- PENDING_REVIEW    = 検証で問題が見つかった。人が確認するまで公開しない
  -- VERIFIED / SINGLE_SOURCE = 公開済み(event_snapshots / event_revisions に入れた)
  -- REJECTED          = 人が確認して誤りとした
  verification_status text not null check (verification_status in ('AWAITING_OFFICIAL', 'PENDING_REVIEW', 'VERIFIED', 'SINGLE_SOURCE', 'REJECTED')),
  -- 検証で見つかった問題のコード(例: OFFICIAL_MISMATCH, OUTLIER_VS_PREVIOUS)
  reasons text[] not null default '{}',
  detail jsonb,
  resolved_at timestamptz,
  resolved_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ingestion_staged_values_revision_field check ((kind = 'REVISION') = (revision_field is not null))
);

-- 同じイベント・同じ種類の未解決の値は1行だけ(取り込みを何度流しても行が増えない)
create unique index uq_ingestion_staged_values_open
  on ingestion_staged_values(event_id, kind, coalesce(revision_field, ''))
  where verification_status in ('AWAITING_OFFICIAL', 'PENDING_REVIEW');
create index idx_ingestion_staged_values_status on ingestion_staged_values(verification_status, created_at);

create trigger trg_ingestion_staged_values_set_updated_at
  before update on ingestion_staged_values
  for each row
  execute function set_updated_at();

-- ---------------------------------------------------------------------
-- 3. official_observations: 照合用の公式統計(FRED / BLS)の観測値
-- ---------------------------------------------------------------------
create table official_observations (
  id bigint generated by default as identity primary key,
  source text not null check (source in ('FRED', 'BLS')),
  series_id text not null,
  -- 観測期間の初日(月次は YYYY-MM-01)
  period_start date not null,
  -- いつ時点の値か(FRED は realtime の日付、BLS は取得日)
  as_of_date date not null,
  value numeric(20, 6),
  -- BLS の脚注 P(preliminary)等
  release_status text not null default 'UNKNOWN' check (release_status in ('PRELIMINARY', 'REVISED', 'FINAL', 'UNKNOWN')),
  fetched_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (source, series_id, period_start, as_of_date)
);

create index idx_official_observations_series on official_observations(source, series_id, period_start);

-- ---------------------------------------------------------------------
-- 4. fx_prices: 2つ目の取得元との照合結果
-- ---------------------------------------------------------------------
-- 既存の行は照合していないので SINGLE_SOURCE。UNVERIFIED の足は Read API が使わない
-- (チャートに出さず、要人発言の値動きは足が無い扱い = DATA_UNAVAILABLE)。欠けた足は補わない。
alter table fx_prices
  add column verification_status text not null default 'SINGLE_SOURCE'
    check (verification_status in ('VERIFIED', 'SINGLE_SOURCE', 'UNVERIFIED')),
  add column cross_check_source text,
  add column cross_check_close numeric(12, 6),
  add column cross_check_diff_pips numeric(10, 2);

comment on column fx_prices.verification_status is
  'VERIFIED = 2つ目の取得元と終値の差が閾値以内。SINGLE_SOURCE = 照合していない(2つ目の取得元に同じ分の足が無い等)。UNVERIFIED = 差が閾値を超えた、または値が不自然。Read API は UNVERIFIED を使わない。';

